export function getActionPlan(selection: { minutes: number; setting: string }): ActionPlan | null {
  const { minutes, setting } = selection;
  if (minutes !== 10 && minutes !== 30 && minutes !== 60) return null;
  if (setting !== "home" && setting !== "nearby" && setting !== "friends") return null;
  const action = ACTIONS[setting];
  return { title: action.title, setting: action.setting, minutes, preparation: action.preparation, steps: action.steps[minutes], note: action.note };
}

export function createInvitation(plan: ActionPlan): string {
  const duration = new Intl.NumberFormat("bn-BD").format(plan.minutes);
  return [
    `একসঙ্গে একটি ছোট কাজ করার আমন্ত্রণ: ${plan.title}।`,
    `প্রায় ${duration} মিনিট সময় নিয়ে ${plan.setting} কাজটি করতে পারি।`,
    "সময় ও জায়গা আমরা আলোচনা করে ঠিক করব।",
    "যা লাগবে: " + plan.preparation + "।",
    ...plan.steps.map((step, index) => `${new Intl.NumberFormat("bn-BD").format(index + 1)}. ${step}`),
    plan.note,
    "এটি কোনো আয়োজকের অনুষ্ঠান নয়; নিজেদের উদ্যোগে করার প্রস্তাব।",
    "পরিকল্পনা: এক ঘণ্টা ভালো কাজ",
  ].join("\n\n");
}
