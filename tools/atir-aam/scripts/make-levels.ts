// Writes lib/levels.ts: node --import tsx tools/atir-aam/scripts/make-levels.ts
// Each level: a plot (size, stones) and a goal stage. For each, the first seed the look-ahead bot clears is kept, with the
// bot's move count as par. The tests replay the bot on every level and check the same count.
import { writeFileSync } from "node:fs";
import { botRun } from "../lib/bot";

type Spec = [size: number, stones: number[], target: number, tight: 0 | 1];
const SPECS: Spec[] = [
  // ১ উঠোন: 4×4, the goal climbs one stage at a time
  [4, [], 2, 0], [4, [], 3, 0], [4, [], 4, 0], [4, [], 5, 0], [4, [], 6, 0], [4, [], 6, 1], [4, [], 7, 0], [4, [], 7, 1],
  // ২ পুকুরপাড়: 4×4 with পাথর
  [4, [6], 5, 0], [4, [9], 6, 0], [4, [5, 10], 6, 0], [4, [12], 7, 0], [4, [1, 14], 7, 0], [4, [6, 9], 7, 1], [4, [3], 8, 0], [4, [0, 15], 8, 0],
  // ৩ আমবাগান: the bigger 5×5 plot
  [5, [12], 6, 0], [5, [6, 18], 7, 0], [5, [2, 10, 14, 22], 7, 1], [5, [12], 8, 0], [5, [0, 4, 20, 24], 8, 0], [5, [7, 11, 13, 17], 8, 1], [5, [12], 9, 0], [5, [6, 8, 16, 18], 9, 0],
];

const rows: string[] = [];
SPECS.forEach(([size, stones, target, tight], index) => {
  for (let seed = (index + 1) * 1000 + 1; seed < (index + 1) * 1000 + 200; seed++) {
    const bot = botRun(seed, size, stones, target);
    if (bot === null) continue;
    rows.push(`  { size: ${size}, stones: [${stones.join(", ")}], target: ${target}, tight: ${!!tight}, seed: ${seed}, bot: ${bot} },`);
    console.log(index + 1, seed, bot);
    return;
  }
  throw new Error(`level ${index + 1}: no seed cleared`);
});

writeFileSync(new URL("../lib/levels.ts", import.meta.url), `// Generated by scripts/make-levels.ts: don't edit by hand. 24 levels in three plots: উঠোন, পুকুরপাড় (with পাথর), আমবাগান (5×5).
// \`bot\` is the look-ahead bot's move count to the goal stage; the stars and the move limit are set from it (lib/game.ts).
export type LevelSpec = { size: number; stones: readonly number[]; target: number; tight: boolean; seed: number; bot: number };
export const LEVELS: readonly LevelSpec[] = [
${rows.join("\n")}
];
`);
