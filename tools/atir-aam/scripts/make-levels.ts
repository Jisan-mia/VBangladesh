// Writes lib/level-seeds.ts: node --import tsx tools/atir-aam/scripts/make-levels.ts [from] [to]
// For each level in lib/levels.ts, the first plot seed that the look-ahead bot clears, and where the casual bot clears at
// least the season's floor, is kept with the bot's move count as par. The tests replay both bots and check the same numbers.
import { writeFileSync } from "node:fs";
import { LEVEL_COUNT, LEVELS, type Level } from "../lib/levels";
import { SEEDS } from "../lib/level-seeds";
import { botPar, casual, rateOf, steady } from "../tests/bot";
import type { Run } from "../lib/rules";

const from = Number(process.argv[2] ?? 1), to = Number(process.argv[3] ?? LEVEL_COUNT);
// season 1: a casual player clears it almost always, and its finale a little less; later: a steady player clears it at
// least this often (the tests assert these over 30 players)
const fits = (level: number, rate: number) => level < 8 ? rate >= 0.95 : level === 8 ? rate >= 0.75 && rate <= 0.93 : level % 8 === 0 ? rate >= 0.5 : rate >= 0.65;
const out: (readonly [number, number])[] = SEEDS.slice();
for (let level = from; level <= to; level++) {
  let found = false;
  for (let seed = level * 1000 + 1; seed < level * 1000 + 60 && !found; seed++) {
    // the rules read the table, so try the candidate in place
    const row = LEVELS[level - 1] as Level;
    row.seed = seed; row.bot = 100000;
    const par = botPar({ v: 2, kind: "level", level, seed, mode: "n" } satisfies Run, 2000);
    if (par === null) continue;
    row.bot = par;
    out[level - 1] = [seed, par];
    const run: Run = { v: 2, kind: "level", level, seed: 0, mode: "n" };
    const { rate, median } = rateOf(run, level <= 8 ? person => casual(person) : person => steady(person), 30);
    console.log(level, seed, par, rate, median);
    if (fits(level, rate)) found = true;
  }
  if (!found) console.log(level, "kept the last candidate");
}
writeFileSync(new URL("../lib/level-seeds.ts", import.meta.url), file(out));
function file(rows: readonly (readonly [number, number])[]) {
  return `// Generated by scripts/make-levels.ts: don't edit by hand. [plot seed, the look-ahead bot's move count to the goal].\nexport const SEEDS: readonly (readonly [number, number])[] = [\n${rows.map(([seed, bot]) => `  [${seed}, ${bot}],`).join("\n")}\n];\n`;
}
