// Writes lib/plates.ts: node --import tsx tools/ponero-ghor/scripts/make-levels.ts
// 3×3 plates are picked so the true shortest solution rises step by step; bigger plates by a rising shuffle length.
// The plates behind old links must never change: the tests pin a checksum of all thirty boards.
// METHOD is the layered solver's own length on each plate (row by row, the way a patient person solves it); the star
// targets build on it, so the strong bot earns three stars on every plate by construction, and the tests prove it.
import { writeFileSync } from "node:fs";
import { place, shuffled, solve, sizeOf, LEVEL_COUNT } from "../lib/board";

const SHORTEST_3 = [2, 3, 4, 6, 8, 10, 12, 15, 18, 21];
const STEPS_4 = [8, 12, 16, 20, 26, 32, 40, 48, 58, 70, 84, 100, 120, 140, 160];
const STEPS_5 = [40, 70, 110, 160, 220];

const rows: Array<[number, number, number]> = [], method: number[] = [];
let before = 0;
for (let level = 1; level <= LEVEL_COUNT; level++) {
  const size = sizeOf(level);
  if (size !== sizeOf(level - 1)) before = 0;
  if (size === 3) {
    const want = SHORTEST_3[level - 1];
    for (let seed = level * 1000 + 1; ; seed++) {
      const steps = want + 2 * (seed % 4);
      if (place(shuffled(3, seed, steps).board, [1, 2, 3, 4, 5, 6, 7, 8])!.length === want) { rows.push([seed, steps, want]); break; }
    }
  } else {
    const steps = size === 4 ? STEPS_4[level - 11] : STEPS_5[level - 26];
    for (let seed = level * 1000 + 1; ; seed++) {
      const par = Math.min(steps, solve(shuffled(size, seed, steps).board).length);
      if (par > before) { rows.push([seed, steps, par]); before = par; break; }
    }
  }
  const [seed, steps] = rows[rows.length - 1];
  method.push(solve(shuffled(size, seed, steps).board).length);
  console.log(level, rows[rows.length - 1], method[method.length - 1]);
}

writeFileSync(new URL("../lib/plates.ts", import.meta.url), `// Generated by scripts/make-levels.ts: don't edit by hand. Each plate: [seed, shuffle steps, par].
// The plate is the solved one shuffled by \`steps\` seeded random slides. Par is the true shortest solution on 3×3, and on
// bigger plates the shorter of the shuffle undone and the solver's own solution. Old links replay on these, so they never change.
export const PLATES: ReadonlyArray<readonly [number, number, number]> = [
${rows.map(row => `  [${row.join(", ")}],`).join("\n")}
];

/** The layered solver's moves on each plate (row by row, the last ৩×৩ exactly). The star targets build on it. */
export const METHOD: readonly number[] = [${method.join(", ")}];
`);
