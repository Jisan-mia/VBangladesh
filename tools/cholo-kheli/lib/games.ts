export function parsePlayerCount(value: string): number | null {
  const digits = value.trim().replace(/[০-৯]/g, (digit) => String(digit.charCodeAt(0) - "০".charCodeAt(0)));
  if (!/^\d+$/.test(digits)) return null;
  const count = Number(digits);
  return Number.isInteger(count) && count >= 2 && count <= 16 ? count : null;
}

export function findGames(selection: { players: number; space: string; equipment: string[] }): Game[] {
  if (!Number.isInteger(selection.players) || selection.players < 2 || selection.players > 16) return [];
  if (!["seated", "courtyard", "field"].includes(selection.space)) return [];
  if (!selection.equipment.every((item) => item === "paper" || item === "chalk" || item === "marker")) return [];
  return games.filter((game) => selection.players >= game.minPlayers && selection.players <= game.maxPlayers
    && (!game.evenTeams || selection.players % 2 === 0)
    && game.spaces.includes(selection.space)
    && game.equipment.every((item) => selection.equipment.includes(item)));
}

export function createGameInvitation(game: Game, players: number): string {
  const number = new Intl.NumberFormat("bn-BD");
  return [
    `চলো খেলি: ${game.title}`, `${number.format(players)} জনের খেলা। মোটামুটি সময়: ${game.duration}।`,
    "কখন, কোথায় খেলব, সবাই মিলে ঠিক করে নেব।", `যা লাগবে: ${game.supplies}।`, `যেভাবে খেলব: ${game.variant}।`,
    ...game.rules.map((rule, index) => `${number.format(index + 1)}. ${rule}`), game.ending,
    `খেয়াল রেখো: ${game.care}`, "কোনো আয়োজক নেই, নিজেরাই মিলে খেলব। চলে এসো!",
  ].join("\n\n");
}
