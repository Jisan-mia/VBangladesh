const pairKey = (a: string, b: string) => (a < b ? `${a}+${b}` : `${b}+${a}`);
export type Recipe = { a: string; b: string; out: string };
export const recipes: readonly Recipe[] = RECIPES.map(line => {
  const [pair, out] = line.split("=");
  const [a, b] = pair.split("+");
  return { a, b, out };
});
const recipeMap = new Map(recipes.map(recipe => [pairKey(recipe.a, recipe.b), recipe.out]));

/** What the pot makes from a and b (order doesn't matter), or undefined. */
export const mix = (a: string, b: string) => recipeMap.get(pairKey(a, b));

